import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const directory = path.join(root, "supabase/migrations");
const output = path.join(root, "supabase/cloud-bootstrap.sql");
const files = readdirSync(directory)
  .filter((file) => file.endsWith(".sql"))
  .sort();
if (!files.length) throw new Error("No versioned migrations were found.");
const versions = new Set();
const sections = files.map((file) => {
  const match = /^(\d{14})_([a-z0-9_]+)\.sql$/.exec(file);
  if (!match || versions.has(match[1]))
    throw new Error(`Invalid or duplicate migration version: ${file}`);
  const [, version, name] = match;
  versions.add(version);
  return `-- Migration: ${file}\n${readFileSync(path.join(directory, file), "utf8").trim()}\n\nINSERT INTO supabase_migrations.schema_migrations(version, name) VALUES ('${version}', '${name}');`;
});
const sql = `-- GENERATED by npm run db:cloud:bundle. Do not edit this file directly.
-- FIRST INSTALL ONLY: run in the SQL Editor of a NEW, EMPTY Supabase project.
-- All application migrations run in one transaction. Existing application
-- schemas or migration histories are rejected; this script never resets data.
-- The version history supports future incremental Supabase CLI migrations.

BEGIN;

DO $pibardos_guard$
BEGIN
  IF to_regclass('auth.users') IS NULL OR to_regprocedure('auth.uid()') IS NULL THEN
    RAISE EXCEPTION 'A Supabase project with Auth is required.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v', 'm', 'f')
  ) OR EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public' AND t.typtype = 'e'
  ) THEN
    RAISE EXCEPTION 'Pibardos bootstrap requires an empty public schema. Use incremental migrations for an existing project.';
  END IF;
END
$pibardos_guard$;

CREATE SCHEMA IF NOT EXISTS supabase_migrations;
CREATE TABLE IF NOT EXISTS supabase_migrations.schema_migrations (
  version text PRIMARY KEY,
  statements text[],
  name text
);
DO $pibardos_history_guard$
BEGIN
  IF EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations) THEN
    RAISE EXCEPTION 'Pibardos bootstrap requires an empty migration history. Use incremental migrations for an existing project.';
  END IF;
END
$pibardos_history_guard$;
REVOKE ALL ON SCHEMA supabase_migrations FROM PUBLIC, anon, authenticated;
REVOKE ALL ON supabase_migrations.schema_migrations FROM PUBLIC, anon, authenticated;

${sections.join("\n\n")}

NOTIFY pgrst, 'reload schema';
COMMIT;

-- Expected: ${files.length} application migrations; every public table has RLS.
SELECT count(*) AS applied_migrations FROM supabase_migrations.schema_migrations;
SELECT count(*) AS application_tables,
       count(*) FILTER (WHERE c.relrowsecurity) AS tables_with_rls
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p');
`;

if (process.argv.slice(2).some((arg) => arg !== "--check"))
  throw new Error("Usage: node scripts/build-cloud-bootstrap.mjs [--check]");
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== sql)
    throw new Error("Cloud bootstrap is stale. Run npm run db:cloud:bundle.");
  console.log(
    `Cloud bootstrap matches all ${files.length} versioned migrations.`,
  );
} else {
  writeFileSync(output, sql);
  console.log(
    `Generated supabase/cloud-bootstrap.sql from ${files.length} migrations.`,
  );
}
